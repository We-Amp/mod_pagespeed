"""Generate lib/html/html5_named_entities.inc from the HTML Standard's table.

Usage:
  curl -sO https://html.spec.whatwg.org/entities.json
  tools/gen-html5-entities.py entities.json > lib/html/html5_named_entities.inc

Each row is {name, first code point, second code point (0 if none), legacy},
sorted by name (byte order) for a binary search.  `name` excludes the leading
'&' and the trailing ';'.  `legacy` is 1 when the standard also accepts the
name without its ';' (the 106 historical names such as "amp" and "copy").
"""

import json
import sys


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    with open(sys.argv[1], encoding="utf-8") as f:
        table = json.load(f)
    rows = {}
    legacy = set()
    for key, value in table.items():
        if not key.startswith("&"):
            raise SystemExit(f"unexpected key {key!r}")
        cps = value["codepoints"]
        if not 1 <= len(cps) <= 2:
            raise SystemExit(f"unexpected code points for {key!r}")
        if key.endswith(";"):
            rows[key[1:-1]] = cps
        else:
            legacy.add(key[1:])
    for name in legacy:
        if name not in rows:
            raise SystemExit(f"legacy name {name!r} has no ';' form")
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Copyright (c) 2024-2026 We-Amp B.V.",
        "",
        "// GENERATED by tools/gen-html5-entities.py from the HTML Standard's",
        "// named character reference table (entities.json). Do not edit.",
        "// Row: {name without '&' and ';', code point, second code point or 0,",
        "//       1 if the name is also recognized without its ';'}.",
        "// Sorted by name in byte order.",
        "",
        "// clang-format off",
    ]
    for name in sorted(rows, key=lambda s: s.encode("ascii")):
        cps = rows[name]
        second = cps[1] if len(cps) == 2 else 0
        flag = 1 if name in legacy else 0
        out.append(f'{{"{name}", 0x{cps[0]:X}, 0x{second:X}, {flag}}},')
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
