"""Generate, or check, the compiled-in known-agent table.

The module classifies a request's User-Agent against a fixed table of AI
agent product tokens (pagespeed/kernel/http/known_agent_table.h). The table
is a build-time snapshot of one file of the optimizer repository, the agent
list `website/src/data/ai-crawlers.json`, at the optimizer commit that
test/system/known-agent-table-pin.json names. That pin is its own: bumping
the system-test optimizer pin never changes the table.

Only each entry's `token` and `kind` are compiled in. Nothing is loaded or
fetched at run time.

Usage:

    # Write the snapshot from a copy of the agent file at the pinned commit.
    tools/gen_known_agent_table.py generate <pin.json> <ai-crawlers.json> \\
        <known_agent_table.inc>

    # Fail (exit 1) when the snapshot is not exactly what `generate` writes
    # from that file, or the file is not the one the pin names.
    tools/gen_known_agent_table.py check <pin.json> <ai-crawlers.json> \\
        <known_agent_table.inc>

    # Fail when the snapshot's header does not name the pin's commit and
    # digest (needs no copy of the agent file).
    tools/gen_known_agent_table.py check-pin <pin.json> <known_agent_table.inc>

    tools/gen_known_agent_table.py --self-test
"""

import hashlib
import json
import os
import re
import sys
import tempfile

KINDS = {
    "training": "kTraining",
    "search": "kSearch",
    "fetcher": "kFetcher",
    "other": "kOther",
}
# A token boundary in a User-Agent (pagespeed/kernel/http/known_agent_table.h).
BOUNDARY = frozenset(" ();/")
COMMIT_RE = re.compile(r"^[0-9a-f]{40}$")
SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
HEADER_RE = re.compile(
    r"^// Source: (\S+) at optimizer commit ([0-9a-f]{40})\n"
    r"// sha256: ([0-9a-f]{64})\n",
    re.M,
)


class TableError(Exception):
    pass


def load_pin(path):
    with open(path, encoding="utf-8") as f:
        pin = json.load(f)
    for key in ("optimizer_commit", "path", "sha256"):
        if not isinstance(pin.get(key), str):
            raise TableError(f"{path}: '{key}' is missing")
    if not COMMIT_RE.match(pin["optimizer_commit"]):
        raise TableError(f"{path}: optimizer_commit is not a full commit id")
    if not SHA256_RE.match(pin["sha256"]):
        raise TableError(f"{path}: sha256 is not a hex digest")
    return pin


def validate_token(token):
    if not isinstance(token, str) or not token:
        raise TableError("an entry has no token")
    if any(ord(c) < 0x21 and c != " " or ord(c) > 0x7E for c in token):
        raise TableError(f"token {token!r}: only printable ASCII is allowed")
    if token[0] in BOUNDARY or token[-1] in BOUNDARY:
        raise TableError(f"token {token!r} starts or ends on a boundary")
    if "  " in token:
        raise TableError(f"token {token!r} has a double space")
    if '"' in token or "\\" in token:
        raise TableError(f"token {token!r} has a quote or a backslash")


def entries(data):
    """(token, kind) pairs, sorted by lower-cased token."""
    try:
        table = json.loads(data)
    except ValueError as e:
        raise TableError(f"agent file is not JSON: {e}")
    if not isinstance(table, list) or not table:
        raise TableError("agent file is not a non-empty list")
    out, seen = [], set()
    for entry in table:
        if not isinstance(entry, dict):
            raise TableError("an entry is not an object")
        token = entry.get("token")
        validate_token(token)
        kind = entry.get("kind")
        if kind not in KINDS:
            raise TableError(f"token {token!r}: unknown kind {kind!r}")
        if token.lower() in seen:
            raise TableError(f"token {token!r} is listed twice")
        seen.add(token.lower())
        out.append((token, kind))
    out.sort(key=lambda e: (e[0].lower(), e[0]))
    return out


def render(pin, data):
    rows = entries(data)
    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Copyright (c) 2026 We-Amp B.V.",
        "//",
        "// GENERATED by tools/gen_known_agent_table.py; do not edit. A drift",
        "// check fails the build when this differs from the pinned agent file",
        "// (test/system/known-agent-table-pin.json).",
        f"// Source: {pin['path']} at optimizer commit {pin['optimizer_commit']}",
        f"// sha256: {hashlib.sha256(data).hexdigest()}",
        "//",
        "// One KNOWN_AGENT(token, kind) per entry, sorted by lower-cased token.",
        f"// {len(rows)} entries.",
        "",
    ]
    for token, kind in rows:
        lines.append(f'KNOWN_AGENT("{token}", {KINDS[kind]})')
    return "\n".join(lines) + "\n"


def read_bytes(path):
    with open(path, "rb") as f:
        return f.read()


def check_pin(pin, inc_text):
    m = HEADER_RE.search(inc_text)
    if m is None:
        raise TableError("the snapshot has no source header; regenerate it")
    path, commit, digest = m.groups()
    if (path, commit, digest) != (pin["path"], pin["optimizer_commit"], pin["sha256"]):
        raise TableError(
            "the snapshot was generated from "
            f"{path}@{commit} (sha256 {digest}), but the pin names "
            f"{pin['path']}@{pin['optimizer_commit']} (sha256 {pin['sha256']}); "
            "regenerate it with tools/gen_known_agent_table.py generate"
        )


def check(pin, data, inc_text):
    digest = hashlib.sha256(data).hexdigest()
    if digest != pin["sha256"]:
        raise TableError(
            f"the agent file's sha256 is {digest}, the pin names {pin['sha256']}: "
            "it is not the pinned file"
        )
    check_pin(pin, inc_text)
    if render(pin, data) != inc_text:
        raise TableError(
            "the snapshot differs from the pinned agent file; regenerate it with "
            "tools/gen_known_agent_table.py generate"
        )


def main(argv):
    if argv[1:] == ["--self-test"]:
        return self_test()
    if len(argv) == 5 and argv[1] in ("generate", "check"):
        pin = load_pin(argv[2])
        data = read_bytes(argv[3])
        if argv[1] == "generate":
            if hashlib.sha256(data).hexdigest() != pin["sha256"]:
                raise TableError("the agent file is not the one the pin names "
                                 "(sha256 differs); update the pin first")
            with open(argv[4], "w", encoding="utf-8", newline="\n") as f:
                f.write(render(pin, data))
            return 0
        with open(argv[4], encoding="utf-8", newline="") as f:
            check(pin, data, f.read())
        print(f"ok: {argv[4]} matches {pin['path']}@{pin['optimizer_commit']}")
        return 0
    if len(argv) == 4 and argv[1] == "check-pin":
        with open(argv[3], encoding="utf-8", newline="") as f:
            check_pin(load_pin(argv[2]), f.read())
        print(f"ok: {argv[3]} names the pinned commit")
        return 0
    print(__doc__, file=sys.stderr)
    return 2


def self_test():
    table = [
        {"token": "GPTBot", "kind": "training", "operator": "x"},
        {"token": "ChatGPT Agent", "kind": "fetcher"},
        {"token": "iaskspider/2.0", "kind": "other"},
    ]
    data = json.dumps(table).encode()
    pin = {
        "optimizer_commit": "a" * 40,
        "path": "website/src/data/ai-crawlers.json",
        "sha256": hashlib.sha256(data).hexdigest(),
    }
    inc = render(pin, data)
    assert 'KNOWN_AGENT("ChatGPT Agent", kFetcher)\nKNOWN_AGENT("GPTBot", kTraining)\n' in inc, inc
    assert "operator" not in inc
    check(pin, data, inc)

    def fails(fn, *args):
        try:
            fn(*args)
        except TableError:
            return True
        return False

    # The pinned file changed: its digest no longer matches.
    changed = data.replace(b"GPTBot", b"GPTBotX")
    assert fails(check, pin, changed, inc)
    # Pin and file both moved on, the snapshot did not.
    moved = dict(pin, sha256=hashlib.sha256(changed).hexdigest())
    assert fails(check, moved, changed, inc)
    assert fails(check_pin, moved, inc)
    # Another commit with the same file still needs a regenerated header.
    assert fails(check_pin, dict(pin, optimizer_commit="b" * 40), inc)
    # A hand edit of the snapshot.
    assert fails(check, pin, data, inc.replace("kTraining", "kSearch"))
    assert fails(check, pin, data, inc + 'KNOWN_AGENT("Extra", kOther)\n')
    # Tokens the matcher cannot use are refused.
    for bad in ["", " GPTBot", "GPTBot/", "(x", "a  b", "café", "a\tb", 'a"b']:
        bad_data = json.dumps([{"token": bad, "kind": "other"}]).encode()
        assert fails(entries, bad_data), bad
    assert fails(entries, json.dumps([{"token": "x", "kind": "nope"}]).encode())
    assert fails(entries, json.dumps([{"token": "x", "kind": "other"},
                                      {"token": "X", "kind": "other"}]).encode())
    assert fails(entries, b"[]")
    # The command line, end to end.
    with tempfile.TemporaryDirectory() as d:
        pin_path = os.path.join(d, "pin.json")
        table_path = os.path.join(d, "table.json")
        inc_path = os.path.join(d, "table.inc")
        with open(pin_path, "w") as f:
            json.dump(pin, f)
        with open(table_path, "wb") as f:
            f.write(data)
        assert main(["x", "generate", pin_path, table_path, inc_path]) == 0
        assert main(["x", "check", pin_path, table_path, inc_path]) == 0
        assert main(["x", "check-pin", pin_path, inc_path]) == 0
        with open(table_path, "wb") as f:
            f.write(changed)
        assert fails(main, ["x", "check", pin_path, table_path, inc_path])
    print("self-test ok")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv))
    except TableError as e:
        print(f"known-agent table: {e}", file=sys.stderr)
        sys.exit(1)
