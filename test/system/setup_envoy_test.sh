start_static_server() {
    local DOC_ROOT="$ENVOY_CONFIG_DIR/www"
    local STATIC_PID_FILE="$ENVOY_CONFIG_DIR/static.pid"
    local STATIC_SERVER_SCRIPT="$SCRIPT_DIR/static_file_server.py"

    # Check if already running
    if [ -f "$STATIC_PID_FILE" ]; then
        local pid=$(cat "$STATIC_PID_FILE")
        if kill -0 "$pid" 2>/dev/null; then
            log_info "Static file server already running (PID: $pid)"
            return 0
        fi
    fi

    # Verify the server script exists
    if [ ! -f "$STATIC_SERVER_SCRIPT" ]; then
        log_error "Static file server script not found: $STATIC_SERVER_SCRIPT"
        return 1
    fi

    log_info "Starting static file server on port 8081..."

    # Use setsid to create a new session, detaching from docker compose exec.
    # This ensures the process survives when docker compose exec exits.
    # Use our custom static_file_server.py which supports directory index (index.html).
    setsid python3 "$STATIC_SERVER_SCRIPT" 8081 "$DOC_ROOT" 127.0.0.1 \
        > "$ENVOY_CONFIG_DIR/logs/static.log" 2>&1 &
    local shell_pid=$!

    # Wait a moment for the process to start
    sleep 1

    # Find the actual process PID (nohup may fork)
    local actual_pid
    actual_pid=$(pgrep -f "static_file_server.py 8081" | head -1)
    if [ -n "$actual_pid" ]; then
        echo "$actual_pid" > "$STATIC_PID_FILE"
        log_info "Static file server started (PID: $actual_pid)"
    elif kill -0 "$shell_pid" 2>/dev/null; then
        echo "$shell_pid" > "$STATIC_PID_FILE"
        log_info "Static file server started (PID: $shell_pid)"
    else
        log_error "Failed to start static file server"
        return 1
    fi
}

stop_static_server() {
    local STATIC_PID_FILE="$ENVOY_CONFIG_DIR/static.pid"
    if [ -f "$STATIC_PID_FILE" ]; then
        local pid=$(cat "$STATIC_PID_FILE")
        if kill -0 "$pid" 2>/dev/null; then
            log_info "Stopping static file server (PID: $pid)..."
            kill "$pid" 2>/dev/null || true
            sleep 0.5
        fi
        rm -f "$STATIC_PID_FILE"
    fi

    # Also kill any remaining static file server processes (fallback)
    local remaining_pids
    remaining_pids=$(pgrep -f "static_file_server.py 8081" 2>/dev/null || true)
    if [ -n "$remaining_pids" ]; then
        log_info "Cleaning up remaining static server processes..."
        pkill -f "static_file_server.py 8081" 2>/dev/null || true
    fi
}

start_envoy() {
    log_info "Starting Envoy..."

    # Stop if running
    stop_envoy_process

    # Start static file server first
    start_static_server || return 1

    # Start Envoy using setsid to create a new session.
    # This is critical when running via 'docker compose exec' - Docker sends
    # SIGTERM to all processes in the exec session when it exits. Using setsid
    # creates a new session (detached from the controlling terminal) so Envoy
    # survives after the setup script and exec session end.
    #
    # Note: We redirect stdout to /dev/null because Envoy logs to --log-path.
    setsid "$ENVOY_BINARY" -c "$ENVOY_CONFIG_FILE" \
        --log-path "$ENVOY_LOG_FILE" \
        --log-level info \
        > /dev/null 2>&1 &

    # Give the process a moment to start
    sleep 1

    # Find the actual Envoy process PID
    local envoy_pid
    envoy_pid=$(pgrep -f "envoy_pagespeed.*$ENVOY_CONFIG_FILE" | head -1)

    if [ -z "$envoy_pid" ]; then
        log_error "Failed to start Envoy - process not found"
        log_info "Checking log file..."
        tail -30 "$ENVOY_LOG_FILE" 2>/dev/null || true
        return 1
    fi

    echo "$envoy_pid" > "$ENVOY_PID_FILE"
    log_info "Envoy started with PID: $envoy_pid"
    log_info "PID file: $ENVOY_PID_FILE"

    # Wait for Envoy to start and be ready to accept connections
    log_info "Waiting for Envoy to be ready..."
    local max_wait=30
    local waited=0
    while [ $waited -lt $max_wait ]; do
        sleep 1
        waited=$((waited + 1))

        # Check if process is still running (use pgrep for reliability)
        if ! pgrep -f "envoy_pagespeed.*$ENVOY_CONFIG_FILE" > /dev/null 2>&1; then
            log_error "Envoy process died during startup"
            log_info "Checking log file..."
            tail -30 "$ENVOY_LOG_FILE" 2>/dev/null || true
            return 1
        fi

        # Check if Envoy is responding
        if curl -s --max-time 2 "http://localhost:$ENVOY_PORT/" > /dev/null 2>&1; then
            log_info "Envoy is responding after ${waited}s"
            break
        fi
    done

    if [ $waited -ge $max_wait ]; then
        log_warn "Envoy may not be fully ready after ${max_wait}s"
    fi

    # Check for PageSpeed header
    if curl -sI "http://localhost:$ENVOY_PORT/mod_pagespeed_example/" 2>/dev/null | grep -qi "X-Page-Speed"; then
        log_info "PageSpeed filter is working!"
    else
        log_warn "PageSpeed header not found (filter may need warm-up)"
    fi

    log_info "Envoy with PageSpeed is running:"
    log_info "  HTTP:  http://localhost:$ENVOY_PORT"
    log_info "  HTTPS: https://localhost:$ENVOY_HTTPS_PORT"
    log_info "  Admin: http://localhost:$ENVOY_ADMIN_PORT"
    log_info "Log file: $ENVOY_LOG_FILE"
    log_info ""
    log_info "Run Python tests with:"
    log_info "  PAGESPEED_SERVER_TYPE=envoy PAGESPEED_PORT=$ENVOY_PORT \\"
    log_info "  PAGESPEED_HTTPS_HOST=localhost PAGESPEED_HTTPS_PORT=$ENVOY_HTTPS_PORT \\"
    log_info "      python3 -m pytest test/system/automatic/test_sanity.py -v"
    log_info ""
    log_info "Or run all tests (including HTTPS):"
    log_info "  ./test/system/run_envoy_tests.sh -v"
}

stop_envoy_process() {
    # First try using PID file
    if [ -f "$ENVOY_PID_FILE" ]; then
        local pid=$(cat "$ENVOY_PID_FILE")
        if kill -0 "$pid" 2>/dev/null; then
            log_info "Stopping Envoy (PID: $pid)..."
            kill "$pid" 2>/dev/null || true
            sleep 1
        fi
        rm -f "$ENVOY_PID_FILE"
    fi

    # Also kill any remaining envoy_pagespeed processes (fallback)
    local remaining_pids
    remaining_pids=$(pgrep -f "envoy_pagespeed" 2>/dev/null || true)
    if [ -n "$remaining_pids" ]; then
        log_info "Cleaning up remaining Envoy processes..."
        pkill -f "envoy_pagespeed" 2>/dev/null || true
        sleep 1
    fi
}

stop_envoy() {
    stop_envoy_process
    stop_static_server
    log_info "Envoy stopped"
}

show_status() {
    local envoy_running=false
    local static_running=false

    if [ -f "$ENVOY_PID_FILE" ]; then
        local pid=$(cat "$ENVOY_PID_FILE")
        if kill -0 "$pid" 2>/dev/null; then
            log_info "Envoy is running (PID: $pid)"
            envoy_running=true

            if curl -sI "http://localhost:$ENVOY_PORT/mod_pagespeed_example/" 2>/dev/null | grep -qi "X-Page-Speed"; then
                log_info "PageSpeed filter is active"
            else
                log_warn "PageSpeed header not detected in response"
            fi
        else
            log_info "Envoy is not running (stale PID file)"
        fi
    else
        log_info "Envoy is not running"
    fi

    local STATIC_PID_FILE="$ENVOY_CONFIG_DIR/static.pid"
    if [ -f "$STATIC_PID_FILE" ]; then
        local pid=$(cat "$STATIC_PID_FILE")
        if kill -0 "$pid" 2>/dev/null; then
            log_info "Static file server is running (PID: $pid)"
            static_running=true
        fi
    fi
}

# Main - only run if not being sourced
# When sourced (e.g., from run_envoy_tests.sh), functions are available
# but commands are not executed automatically
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
case "${1:-start}" in
    start)
        check_binary || exit 1
        setup_directories
        setup_test_content
        generate_tls_certs || exit 1
        generate_envoy_config
        start_envoy
        ;;
    stop)
        stop_envoy
        ;;
    status)
        show_status
        ;;
    restart)
        stop_envoy
        sleep 1
        check_binary || exit 1
        start_envoy
        ;;
    *)
        echo "Usage: $0 [start|stop|status|restart]"
        exit 1
        ;;
esac
fi
