#!/bin/bash
#
# Sets up Envoy with PageSpeed filter for running Python system tests.
#
# Usage (inside Docker container):
#   ./test/system/setup_envoy_test.sh [start|stop|status]
#
# After starting, run Python tests with:
#   PAGESPEED_SERVER_TYPE=envoy PAGESPEED_PORT=8080 \
#       python3 -m pytest test/system/automatic/ -v
#

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

# Configuration
ENVOY_BINARY="$PROJECT_ROOT/bazel-bin/pagespeed/envoy/envoy_pagespeed"
ENVOY_CONFIG_DIR="${ENVOY_CONFIG_DIR:-/tmp/envoy_pagespeed_test}"
ENVOY_PID_FILE="$ENVOY_CONFIG_DIR/envoy.pid"
ENVOY_LOG_FILE="$ENVOY_CONFIG_DIR/envoy.log"
ENVOY_CONFIG_FILE="$ENVOY_CONFIG_DIR/envoy.yaml"
CACHE_DIR="$ENVOY_CONFIG_DIR/cache"
# Default PageSpeed cache directory (must match envoy_rewrite_driver_factory.cc)
PAGESPEED_CACHE_DIR="/tmp/envoy_pagespeed_cache"

# Ports
ENVOY_PORT="${ENVOY_PORT:-8080}"
ENVOY_HTTPS_PORT="${ENVOY_HTTPS_PORT:-8443}"
ENVOY_ADMIN_PORT="${ENVOY_ADMIN_PORT:-9901}"

# TLS configuration
TLS_CERT_FILE="$ENVOY_CONFIG_DIR/certs/server.crt"
TLS_KEY_FILE="$ENVOY_CONFIG_DIR/certs/server.key"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

log_info() {
    echo -e "${GREEN}[INFO]${NC} $1"
}

log_warn() {
    echo -e "${YELLOW}[WARN]${NC} $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

check_binary() {
    if [ ! -f "$ENVOY_BINARY" ]; then
        log_error "Envoy binary not found at $ENVOY_BINARY"
        log_info "Build it first with:"
        log_info "  bazel build --config=gcc --jobs=2 //pagespeed/envoy:envoy_pagespeed"
        log_info ""
        log_warn "Note: Building Envoy requires significant memory (16GB+ recommended)"
        return 1
    fi
    return 0
}

generate_tls_certs() {
    log_info "Generating self-signed TLS certificates..."

    local CERT_DIR="$ENVOY_CONFIG_DIR/certs"
    mkdir -p "$CERT_DIR"

    # Check if certs already exist and are valid
    if [ -f "$TLS_CERT_FILE" ] && [ -f "$TLS_KEY_FILE" ]; then
        # Check if cert is still valid (not expired)
        if openssl x509 -checkend 86400 -noout -in "$TLS_CERT_FILE" 2>/dev/null; then
            log_info "TLS certificates already exist and are valid"
            return 0
        fi
        log_info "Existing certificates expired, regenerating..."
    fi

    # Generate self-signed certificate valid for 365 days
    # Subject includes localhost and common test hostnames
    openssl req -x509 -newkey rsa:2048 \
        -keyout "$TLS_KEY_FILE" \
        -out "$TLS_CERT_FILE" \
        -days 365 \
        -nodes \
        -subj "/C=US/ST=Test/L=Test/O=PageSpeed/CN=localhost" \
        -addext "subjectAltName=DNS:localhost,DNS:127.0.0.1,IP:127.0.0.1" \
        2>/dev/null

    if [ $? -eq 0 ]; then
        log_info "TLS certificates generated:"
        log_info "  Certificate: $TLS_CERT_FILE"
        log_info "  Private key: $TLS_KEY_FILE"
    else
        log_error "Failed to generate TLS certificates"
        return 1
    fi
}

setup_directories() {
    log_info "Setting up directories..."
    mkdir -p "$ENVOY_CONFIG_DIR"
    mkdir -p "$CACHE_DIR"
    mkdir -p "$ENVOY_CONFIG_DIR/logs"
    # Create PageSpeed cache directory for CycloneCache
    mkdir -p "$PAGESPEED_CACHE_DIR"
}

setup_test_content() {
    log_info "Setting up test content..."

    # Create document root
    local DOC_ROOT="$ENVOY_CONFIG_DIR/www"
    mkdir -p "$DOC_ROOT"

    # Copy test content
    if [ -d "$PROJECT_ROOT/install/mod_pagespeed_example" ]; then
        rm -rf "$DOC_ROOT/mod_pagespeed_example"
        cp -r "$PROJECT_ROOT/install/mod_pagespeed_example" "$DOC_ROOT/"
    else
        log_warn "mod_pagespeed_example not found in install/"
    fi

    if [ -d "$PROJECT_ROOT/install/mod_pagespeed_test" ]; then
        rm -rf "$DOC_ROOT/mod_pagespeed_test"
        cp -r "$PROJECT_ROOT/install/mod_pagespeed_test" "$DOC_ROOT/"
    else
        log_warn "mod_pagespeed_test not found in install/"
    fi

    if [ -d "$PROJECT_ROOT/install/do_not_modify" ]; then
        rm -rf "$DOC_ROOT/do_not_modify"
        cp -r "$PROJECT_ROOT/install/do_not_modify" "$DOC_ROOT/"
    fi

    # Create a simple index.html if nothing exists
    if [ ! -f "$DOC_ROOT/index.html" ]; then
        echo "<html><body><h1>PageSpeed Envoy Test Server</h1></body></html>" > "$DOC_ROOT/index.html"
    fi
}

