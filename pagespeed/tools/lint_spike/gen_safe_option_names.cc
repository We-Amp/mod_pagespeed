// Build-time generator: reads the console's SAFE_OPTION_NAMES list and its
// SECRET_NAME pattern from the TypeScript sources and writes a C++ include
// with the names whose values the lint may print (in the set AND not
// matching SECRET_NAME, the console's two-part rule).  Fails the build when
// either input cannot be found, so a format change cannot silently unmask.
//
// usage: gen_safe_option_names <safe-option-names.ts> <diagnostics.ts> <out>

#include <cstdio>
#include <fstream>
#include <regex>
#include <set>
#include <sstream>
#include <string>
#include <vector>

namespace {

bool ReadFile(const char* path, std::string* out) {
  std::ifstream in(path, std::ios::binary);
  if (!in) return false;
  std::ostringstream ss;
  ss << in.rdbuf();
  *out = ss.str();
  return true;
}

int Fail(const char* msg) {
  std::fprintf(stderr, "gen_safe_option_names: %s\n", msg);
  return 1;
}

}  // namespace

int main(int argc, char** argv) {
  if (argc != 4) return Fail("usage: <safe-option-names.ts> <diagnostics.ts> <out>");
  std::string names_ts, diag_ts;
  if (!ReadFile(argv[1], &names_ts)) return Fail("cannot read names file");
  if (!ReadFile(argv[2], &diag_ts)) return Fail("cannot read diagnostics file");

  const std::string open = "SAFE_OPTION_NAMES: ReadonlySet<string> = new Set([";
  size_t b = names_ts.find(open);
  if (b == std::string::npos) return Fail("SAFE_OPTION_NAMES opener not found");
  b += open.size();
  size_t e = names_ts.find("]);", b);
  if (e == std::string::npos) return Fail("SAFE_OPTION_NAMES closer not found");
  std::string body = names_ts.substr(b, e - b);

  // Every non-blank line must be exactly one "Name", entry: anything else is
  // a format change this generator does not understand.
  std::vector<std::string> names;
  std::istringstream lines(body);
  std::string line;
  const std::regex entry("^\\s*\"([A-Za-z0-9_]+)\",?\\s*$");
  while (std::getline(lines, line)) {
    if (!line.empty() && line.back() == '\r') line.pop_back();
    if (line.find_first_not_of(" \t") == std::string::npos) continue;
    std::smatch m;
    if (!std::regex_match(line, m, entry)) {
      return Fail("unrecognised line inside SAFE_OPTION_NAMES");
    }
    names.push_back(m[1]);
  }
  if (names.empty()) return Fail("SAFE_OPTION_NAMES is empty");

  const std::regex secret_decl("const SECRET_NAME = /(.*)/i;");
  std::smatch sm;
  if (!std::regex_search(diag_ts, sm, secret_decl)) {
    return Fail("SECRET_NAME pattern not found");
  }
  const std::string pattern = sm[1];
  std::regex secret(pattern, std::regex::ECMAScript | std::regex::icase);

  std::set<std::string> safe;
  int excluded = 0;
  for (const std::string& n : names) {
    if (std::regex_search(n, secret)) {
      ++excluded;
      continue;
    }
    safe.insert(n);
  }

  std::ofstream out(argv[3], std::ios::binary);
  out << "// Generated by gen_safe_option_names from safe-option-names.ts and\n"
         "// diagnostics.ts SECRET_NAME. Do not edit.\n";
  out << "static const int kSafeOptionNamesTsCount = " << names.size() << ";\n";
  out << "static const int kSafeOptionNamesSecretExcluded = " << excluded
      << ";\n";
  out << "static const char* const kSafeOptionNames[] = {\n";
  for (const std::string& n : safe) out << "    \"" << n << "\",\n";
  out << "};\n";
  return out.good() ? 0 : Fail("write failed");
}
