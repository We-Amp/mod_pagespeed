// Build-time generator for `pagespeed lint`'s value masking.  Reads the admin
// console's SAFE_OPTION_NAMES list (safe-option-names.ts) and its SECRET_NAME
// pattern (diagnostics.ts) and writes a C++ include with the option names
// whose values the linter may print: in the list AND not matching
// SECRET_NAME, the console's two-part rule.  There is no second list: what is
// safe to show is edited in safe-option-names.ts only.
//
// Fails (and so fails the build) when either input is not in the format this
// generator understands, so a format change cannot silently unmask a value.
//
// usage: gen_safe_option_names <safe-option-names.ts> <diagnostics.ts> <out>

#include <cstdio>
#include <fstream>
#include <regex>
#include <set>
#include <sstream>
#include <string>
#include <vector>

namespace {

bool ReadFile(const char* path, std::string* out) {
  std::ifstream in(path, std::ios::binary);
  if (!in) {
    return false;
  }
  std::ostringstream ss;
  ss << in.rdbuf();
  *out = ss.str();
  return true;
}

int Fail(const char* msg) {
  std::fprintf(stderr, "gen_safe_option_names: %s\n", msg);
  return 1;
}

}  // namespace

int main(int argc, char** argv) {
  if (argc != 4) {
    return Fail("usage: <safe-option-names.ts> <diagnostics.ts> <out>");
  }
  std::string names_ts;
  std::string diag_ts;
  if (!ReadFile(argv[1], &names_ts)) {
    return Fail("cannot read the names file");
  }
  if (!ReadFile(argv[2], &diag_ts)) {
    return Fail("cannot read the diagnostics file");
  }

  const std::string open = "SAFE_OPTION_NAMES: ReadonlySet<string> = new Set([";
  size_t begin = names_ts.find(open);
  if (begin == std::string::npos ||
      names_ts.find(open, begin + 1) != std::string::npos) {
    return Fail("expected exactly one SAFE_OPTION_NAMES opener");
  }
  begin += open.size();
  const size_t end = names_ts.find("]);", begin);
  if (end == std::string::npos) {
    return Fail("SAFE_OPTION_NAMES closer not found");
  }
  const std::string body = names_ts.substr(begin, end - begin);

  // Every non-blank line must be exactly one "Name", entry: anything else
  // (two entries on a line, a comment, single quotes) is a format change this
  // generator does not understand.
  std::vector<std::string> names;
  std::istringstream lines(body);
  std::string line;
  const std::regex entry("^\\s*\"([A-Za-z][A-Za-z0-9_]*)\",?\\s*$");
  while (std::getline(lines, line)) {
    if (!line.empty() && line.back() == '\r') {
      line.pop_back();
    }
    if (line.find_first_not_of(" \t") == std::string::npos) {
      continue;
    }
    std::smatch m;
    if (!std::regex_match(line, m, entry)) {
      return Fail("unrecognised line inside SAFE_OPTION_NAMES");
    }
    names.push_back(m[1]);
  }
  if (names.empty()) {
    return Fail("SAFE_OPTION_NAMES is empty");
  }

  const std::regex secret_decl("const SECRET_NAME = /(.*)/i;");
  std::smatch sm;
  if (!std::regex_search(diag_ts, sm, secret_decl)) {
    return Fail("SECRET_NAME pattern not found");
  }
  const std::string pattern = sm[1];
  if (pattern.empty()) {
    return Fail("SECRET_NAME pattern is empty");
  }
  const std::regex secret(pattern, std::regex::ECMAScript | std::regex::icase);

  std::set<std::string> safe;
  int excluded = 0;
  for (const std::string& n : names) {
    if (std::regex_search(n, secret)) {
      ++excluded;
      continue;
    }
    safe.insert(n);
  }
  if (safe.size() + excluded != names.size()) {
    return Fail("duplicate entry in SAFE_OPTION_NAMES");
  }

  std::ofstream out(argv[3], std::ios::binary);
  out << "// Generated by gen_safe_option_names from safe-option-names.ts and\n"
         "// the SECRET_NAME pattern in diagnostics.ts. Do not edit.\n";
  out << "inline constexpr int kSafeOptionNamesTsCount = " << names.size()
      << ";\n";
  out << "inline constexpr int kSafeOptionNamesSecretExcluded = " << excluded
      << ";\n";
  out << "inline constexpr const char* kSafeOptionNames[] = {\n";
  for (const std::string& n : safe) {
    out << "    \"" << n << "\",\n";
  }
  out << "};\n";
  out << "inline constexpr char kSecretNamePattern[] = R\"re(" << pattern
      << ")re\";\n";
  return out.good() ? 0 : Fail("write failed");
}
